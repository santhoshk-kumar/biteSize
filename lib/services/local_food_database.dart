import '../models/nutrition.dart';

/// Representation of a food item in the local offline database.
class LocalFoodItem {
  const LocalFoodItem({
    required this.id,
    required this.name,
    required this.aliases,
    required this.defaultQuantity,
    required this.defaultUnit,
    required this.gramsPerUnit,
    required this.caloriesPerUnit,
    required this.proteinPerUnit,
    required this.carbsPerUnit,
    required this.fatPerUnit,
    this.fiberPerUnit = 0.0,
    this.sugarPerUnit = 0.0,
    this.saturatedFatGPerUnit = 0.0,
    this.cholesterolMgPerUnit = 0.0,
    // Minerals
    this.sodiumMgPerUnit = 0.0,
    this.potassiumMgPerUnit = 0.0,
    this.calciumMgPerUnit = 0.0,
    this.ironMgPerUnit = 0.0,
    this.magnesiumMgPerUnit = 0.0,
    this.phosphorusMgPerUnit = 0.0,
    this.zincMgPerUnit = 0.0,
    this.seleniumUgPerUnit = 0.0,
    // Vitamins
    this.vitaminAUgPerUnit = 0.0,
    this.vitaminCMgPerUnit = 0.0,
    this.vitaminDUgPerUnit = 0.0,
    this.vitaminEMgPerUnit = 0.0,
    this.vitaminKUgPerUnit = 0.0,
    this.vitaminB1MgPerUnit = 0.0,
    this.vitaminB2MgPerUnit = 0.0,
    this.vitaminB3MgPerUnit = 0.0,
    this.vitaminB5MgPerUnit = 0.0,
    this.vitaminB6MgPerUnit = 0.0,
    this.vitaminB7UgPerUnit = 0.0,
    this.folateUgPerUnit = 0.0,
    this.vitaminB12UgPerUnit = 0.0,
    this.cholineMgPerUnit = 0.0,
    this.suggestedMealType = MealType.lunch,
    this.category = 'General',
  });

  final String id;
  final String name;
  final List<String> aliases;
  final double defaultQuantity;
  final String defaultUnit;
  final double gramsPerUnit;
  final double caloriesPerUnit;
  final double proteinPerUnit;
  final double carbsPerUnit;
  final double fatPerUnit;
  final double fiberPerUnit;
  final double sugarPerUnit;
  final double saturatedFatGPerUnit;
  final double cholesterolMgPerUnit;
  final double sodiumMgPerUnit;
  final double potassiumMgPerUnit;
  final double calciumMgPerUnit;
  final double ironMgPerUnit;
  final double magnesiumMgPerUnit;
  final double phosphorusMgPerUnit;
  final double zincMgPerUnit;
  final double seleniumUgPerUnit;
  final double vitaminAUgPerUnit;
  final double vitaminCMgPerUnit;
  final double vitaminDUgPerUnit;
  final double vitaminEMgPerUnit;
  final double vitaminKUgPerUnit;
  final double vitaminB1MgPerUnit;
  final double vitaminB2MgPerUnit;
  final double vitaminB3MgPerUnit;
  final double vitaminB5MgPerUnit;
  final double vitaminB6MgPerUnit;
  final double vitaminB7UgPerUnit;
  final double folateUgPerUnit;
  final double vitaminB12UgPerUnit;
  final double cholineMgPerUnit;
  final MealType suggestedMealType;
  final String category;

  FoodItem toFoodItem({
    double multiplier = 1.0,
    double? customQuantity,
    String? customUnit,
    double? customGrams,
  }) {
    final qty = customQuantity ?? (defaultQuantity * multiplier);
    final unit = customUnit ?? defaultUnit;
    final g = customGrams ?? (gramsPerUnit * multiplier);
    final note = customUnit != null && (customUnit == 'ml' || customUnit == 'g')
        ? '${qty.round()}$customUnit serving'
        : '${g.round()}g standard serving ($unit)';
    return FoodItem(
      id: '${id}_${DateTime.now().microsecondsSinceEpoch}',
      name: name,
      quantity: qty,
      unit: unit,
      estimatedGrams: g,
      macros: MacroNutrients(
        calories: caloriesPerUnit * multiplier,
        proteinG: proteinPerUnit * multiplier,
        carbsG: carbsPerUnit * multiplier,
        fatG: fatPerUnit * multiplier,
        fiberG: fiberPerUnit * multiplier,
        sugarG: sugarPerUnit * multiplier,
        saturatedFatG: saturatedFatGPerUnit * multiplier,
        cholesterolMg: cholesterolMgPerUnit * multiplier,
        sodiumMg: sodiumMgPerUnit * multiplier,
        potassiumMg: potassiumMgPerUnit * multiplier,
        calciumMg: calciumMgPerUnit * multiplier,
        ironMg: ironMgPerUnit * multiplier,
        magnesiumMg: magnesiumMgPerUnit * multiplier,
        phosphorusMg: phosphorusMgPerUnit * multiplier,
        zincMg: zincMgPerUnit * multiplier,
        seleniumUg: seleniumUgPerUnit * multiplier,
        vitaminAUg: vitaminAUgPerUnit * multiplier,
        vitaminCMg: vitaminCMgPerUnit * multiplier,
        vitaminDUg: vitaminDUgPerUnit * multiplier,
        vitaminEMg: vitaminEMgPerUnit * multiplier,
        vitaminKUg: vitaminKUgPerUnit * multiplier,
        vitaminB1Mg: vitaminB1MgPerUnit * multiplier,
        vitaminB2Mg: vitaminB2MgPerUnit * multiplier,
        vitaminB3Mg: vitaminB3MgPerUnit * multiplier,
        vitaminB5Mg: vitaminB5MgPerUnit * multiplier,
        vitaminB6Mg: vitaminB6MgPerUnit * multiplier,
        vitaminB7Ug: vitaminB7UgPerUnit * multiplier,
        folateUg: folateUgPerUnit * multiplier,
        vitaminB12Ug: vitaminB12UgPerUnit * multiplier,
        cholineMg: cholineMgPerUnit * multiplier,
      ),
      confidence: 'high',
      notes: note,
    );
  }
}

