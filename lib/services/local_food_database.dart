  /// Finds the best matching food item from the offline database.
  static LocalFoodItem? findMatch(String query) {
    final clean = query.trim().toLowerCase();
    if (clean.isEmpty) return null;

    // 1. Direct exact alias match
    for (final item in items) {
      for (final a in item.aliases) {
        if (a == clean) return item;
      }
    }

    // 2. Substring containment match (prefer longer aliases first to avoid greedy prefix bugs like 'milk' before 'milk tea')
    LocalFoodItem? bestMatch;
    int bestMatchLength = 0;

    for (final item in items) {
      for (final a in item.aliases) {
        if (clean == a || clean.startsWith('$a ') || clean.endsWith(' $a') || clean.contains(' $a ')) {
          if (a.length > bestMatchLength) {
            bestMatch = item;
            bestMatchLength = a.length;
          }
        }
      }
    }
    if (bestMatch != null) return bestMatch;

    // 3. Relaxed contains (also preferring longer alias matches)
    for (final item in items) {
      for (final a in item.aliases) {
        if (clean.contains(a)) {
          if (a.length > bestMatchLength) {
            bestMatch = item;
            bestMatchLength = a.length;
          }
        }
      }
    }

    return bestMatch;
  }
